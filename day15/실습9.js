const 구독로그테이블 = [{ 구독번호: 1, 회원코드: 1, 상품코드: 1, 구독종료일: '2025-06-20' },
{ 구독번호: 2, 회원코드: 2, 상품코드: 2, 구독종료일: '2025-06-15' }];
// 구독로그테이블에 회원코드 없으면 구독 내역 없음

const today = '2025-06-17';

// (2) 하나씩 조회 중인 회원정보가 구독로그테이블(배열) 내 '회원코드'가 일치한 정보확인

html = `<h1> 회원 구독 상태 대시보드 </h1> <hr/>`
document.write(html);
for (let i = 0; i < 회원테이블.length; i++) {
    let 회원 = 회원테이블[i];
    let 구독 = false;
    let 구독상품코드 = -1;
    let 구독활성화 = '';
    let html = '';

    html = `<h3> ${회원.회원이름} </h3>`;

    for (let j = 0; j < 구독로그테이블.length; j++) {
        let 구독로그 = 구독로그테이블[j];
        if (구독로그.회원코드 == 회원.회원코드) {
            구독 = true;
            구독상품코드 = 구독로그.상품코드;
            구독활성화 = (구독로그.구독종료일 < today) ? "만료" : "활성";
        }
    }

    if (구독) {
        let 상품찾음 = false;
        for (let s = 0; s < 구독상품테이블.length; s++) {
            let 상품정보 = 구독상품테이블[s];
            if (상품정보.상품코드 == 구독상품코드) {
                html += `<p> 구독상품 : ${상품정보.상품명} ${상품정보.가격} </p>`;
                html += `<p> 상태 : ${구독활성화}  </p> <hr/>`;
                상품찾음 = true;
                break;
            }
        }
        if (!상품찾음) {
            html += `<div> ${회원.회원이름} 회원의 구독상품 정보를 찾을 수 없습니다. </div>`;
        }
    } else {
        html += `<div> ${회원.회원코드}번 ${회원.회원이름} 회원은 구독 내역이 없습니다. </div>`;
    }

    document.write(html);
}


